"""Synthetic shape library — the controlled dataset of README section 13.

The project studies *mathematical mechanisms*, so the dataset is synthetic and
exactly known: every shape is a deterministic function of its parameters, the
transformed versions are generated by :meth:`AffineTransform.random_invertible`,
and the ground-truth correspondence between an image and its transform is the
point index.

The library deliberately contains both **generic** shapes (random point sets,
asymmetric blobs) and **highly structured** ones (grids, regular polygons,
letter-like shapes).  The distinction matters for later experiments: a regular
grid has many collinear triples and many parallel segment pairs, so the
relation-based invariants of ``invariants.py`` are *non-vacuous* on it — which
is exactly what makes it a useful test case rather than a vacuous one.
"""

