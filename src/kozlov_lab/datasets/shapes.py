# --------------------------------------------------------------------------- #
# polygons and simple figures
# --------------------------------------------------------------------------- #
def triangle_demo(name: str = "triangle_demo") -> PointSet2D:
    """The 4-point example printed in README section 4's JSON snippet."""
    return PointSet2D([[0, 0], [2, 0], [0, 1], [1, 0.5]], name=name)


def triangle() -> PointSet2D:
    """Three non-collinear points — the minimal image that admits a frame."""
    return PointSet2D([[-1.0, -0.6], [1.4, -0.4], [0.2, 1.3]], name="triangle")


def _polygon(vertices: list[list[float]], name: str) -> PointSet2D:
    return PointSet2D(vertices, name=name)


def square(side: float = 2.0, *, n_per_side: int = 1) -> PointSet2D:
    """Square outline.

    With ``n_per_side > 1`` the sides carry additional points, which creates
    collinear triples — useful because it makes the collinearity invariant of
    `invariants.py` *testable* instead of vacuous.
    """
    pts: list[list[float]] = []
    corners = [(0.0, 0.0), (side, 0.0), (side, side), (0.0, side)]
    for index in range(4):
        ax, ay = corners[index]
        bx, by = corners[(index + 1) % 4]
        for step in range(n_per_side):
            frac = step / n_per_side
            pts.append([ax + frac * (bx - ax), ay + frac * (by - ay)])
    return _polygon(pts, f"square{'' if n_per_side == 1 else f'_{n_per_side}x'}")


def rectangle(width: float = 3.0, height: float = 1.0) -> PointSet2D:
    return _polygon(
        [[0, 0], [width, 0], [width, height], [0, height]],
        f"rectangle_{width:g}x{height:g}",
    )


def parallelogram(skew: float = 0.8) -> PointSet2D:
    """A non-rectangular parallelogram — the canonical affine image of a square."""
    return _polygon(
        [[0, 0], [2.0, 0], [2.0 + skew, 1.4], [skew, 1.4]],
        f"parallelogram_{skew:g}",
    )


def pentagon(radius: float = 1.0, *, rotate_deg: float = 0.0) -> PointSet2D:
    return _regular_polygon(5, radius, rotate_deg, "pentagon")


def star(points: int = 5, outer: float = 1.0, inner: float = 0.4) -> PointSet2D:
    """Concave star polygon — has no collinear triples, so relation rows go vacuous."""
    verts: list[list[float]] = []
    for k in range(2 * points):
        r = outer if k % 2 == 0 else inner
        angle = math.pi * k / points - math.pi / 2
        verts.append([r * math.cos(angle), r * math.sin(angle)])
    return _polygon(verts, f"star{points}")


def letter_l(scale: float = 1.0) -> PointSet2D:
    """Letter-like shape: two collinear arms sharing a corner.

    A grid of samples along the two arms, so the shape is *thin*.  Thin shapes
    are the interesting stress case for frame conditioning.
    """
    pts: list[list[float]] = []
    for k in range(5):
        pts.append([0.0, k * 0.5 * scale])  # vertical arm
    for k in range(1, 5):
        pts.append([k * 0.5 * scale, 0.0])  # horizontal arm
    return _polygon(pts, "letter_L")


def grid(nx: int = 5, ny: int = 5, *, spacing: float = 1.0) -> PointSet2D:
    """Regular grid — the densest source of collinear triples and parallel pairs."""
    pts = [[i * spacing, j * spacing] for j in range(ny) for i in range(nx)]
    return _polygon(pts, f"grid_{nx}x{ny}")


def circle(n: int = 12, radius: float = 1.0, *, rotate_deg: float = 0.0) -> PointSet2D:
    return _regular_polygon(n, radius, rotate_deg, f"circle_{n}")

def _regular_polygon(
    n: int, radius: float, rotate_deg: float, name: str
) -> PointSet2D:
    if n < 3:
        raise ValueError("a regular polygon needs at least 3 vertices")
    base = math.radians(rotate_deg)
    verts = [
        [radius * math.cos(base + 2 * math.pi * k / n), radius * math.sin(base + 2 * math.pi * k / n)]
        for k in range(n)
    ]
    return _polygon(verts, name)


# --------------------------------------------------------------------------- #
# irregular / random shapes
# --------------------------------------------------------------------------- #
def random_points(
    n: int = 8,
    *,
    seed: int | None = None,
    box: tuple[float, float] = (-1.0, 1.0),
    jitter_free: bool = True,
) -> PointSet2D:
    """Uniform random point set.

    ``jitter_free`` rejects samples that would create coincident points, so the
    returned set has cardinality exactly ``n`` (important: a *set* of ``n``
    random points has cardinality ``n`` with probability 1, but a finite
    floating-point draw can still collide).
    """
    g = np.random.default_rng(seed)
    lo, hi = box
    attempts = 0
    pts: list[list[float]] = []
    while len(pts) < n:
        candidate = [float(g.uniform(lo, hi)), float(g.uniform(lo, hi))]
        if not jitter_free or all(
            math.hypot(candidate[0] - p[0], candidate[1] - p[1]) > 1e-9 for p in pts
        ):
            pts.append(candidate)
        attempts += 1
        if attempts > 100 * n:  # pragma: no cover - defensive
            raise RuntimeError("random_points: could not place distinct points")
    return _polygon(pts, f"random_{n}")


def asymmetric_shape() -> PointSet2D:
    """A shape with no symmetry at all — the hardest case for accidental matches."""
    return _polygon(
        [
            [0.0, 0.0],
            [1.7, 0.3],
            [2.1, 1.6],
            [1.1, 2.4],
            [0.2, 2.0],
            [0.6, 0.9],
        ],
        "asymmetric",
    )


def collinear_chain(n: int = 5, *, spacing: float = 1.0) -> PointSet2D:
    """All points on one line: an image that admits **no** affine frame.

    Required by README section 19's test matrix ("共线点").  Downstream code
    must report this explicitly rather than produce a garbage frame.
    """
    return PointSet2D([[k * spacing, 2.0 * k * spacing] for k in range(n)], name="collinear_chain")


def near_collinear_triangle(sine: float = 1e-12, *, scale: float = 1.0) -> PointSet2D:
    """Triangle whose collinearity sine is exactly ``sine``.

    Built directly from the definition, so the conditioning of the resulting
    frame is known analytically: ``cond([B-A, C-A]) ~ 1/sine``.  Used by the
    numerical-stability tests to check that the code reports an attainable
    accuracy instead of pretending ``1e-9`` is always reachable.
    """
    if not (0.0 < sine <= 1.0):
        raise ValueError("sine must lie in (0, 1]")
    cos = math.sqrt(max(0.0, 1.0 - sine * sine))
    return PointSet2D(
        [[0.0, 0.0], [scale, 0.0], [scale * cos, scale * sine]],
        name=f"near_collinear_{sine:g}",
    )


# --------------------------------------------------------------------------- #
# three-dimensional point sets (used from Phase 6 on)
# --------------------------------------------------------------------------- #
def cube_3d(edge: float = 1.0) -> np.ndarray:
    """The 8 vertices of a cube as an ``(8, 3)`` array."""
    half = edge / 2.0
    return np.array(
        [[sx * half, sy * half, sz * half] for sx in (-1, 1) for sy in (-1, 1) for sz in (-1, 1)],
        dtype=np.float64,
    )


def pyramid_3d(height: float = 1.5, base: float = 1.2) -> np.ndarray:
    """Square pyramid vertices as a ``(5, 3)`` array (apex first)."""
    b = base / 2.0
    return np.array(
        [[0.0, 0.0, height], [-b, -b, 0.0], [b, -b, 0.0], [b, b, 0.0], [-b, b, 0.0]],
        dtype=np.float64,
    )


# --------------------------------------------------------------------------- #
# registry (consumed by the GUI's "generate example" buttons)
# --------------------------------------------------------------------------- #
SHAPES: dict[str, Callable[[], PointSet2D]] = {
    "triangle_demo": triangle_demo,
    "triangle": triangle,
    "square": square,
    "square_3x": lambda: square(n_per_side=3),
    "rectangle": rectangle,
    "parallelogram": parallelogram,
    "pentagon": pentagon,
    "star5": star,
    "star7": lambda: star(7, 1.0, 0.55),
    "letter_L": letter_l,
    "grid_5x5": grid,
    "grid_6x4": lambda: grid(6, 4),
    "circle_12": circle,
    "asymmetric": asymmetric_shape,
    "collinear_chain": collinear_chain,
    "random_8": lambda: random_points(8, seed=20261001),
    "random_20": lambda: random_points(20, seed=7),
}


def shape_names() -> list[str]:
    """Sorted list of registry keys."""
    return sorted(SHAPES)


def build_shape(name: str) -> PointSet2D:
    """Instantiate a registered shape by name.

    Raises
    ------
    KeyError
        With the list of valid names, so the GUI can show a helpful message.
    """
    if name not in SHAPES:
        raise KeyError(f"unknown shape {name!r}; available: {', '.join(shape_names())}")
    shape = SHAPES[name]()
    return shape.with_points(shape.as_array(), name=name)
